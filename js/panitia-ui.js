let imageObserver = null;

function setupImageObserver() {
  if (imageObserver) {
    imageObserver.disconnect();
  }

  document.querySelectorAll('img.lazy-panitia-img').forEach((img) => {
    img.loading = 'lazy';
    img.decoding = 'async';
    img.style.opacity = '1';
    img.dataset.loaded = 'true';
  });
}

